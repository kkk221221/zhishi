TCM_BOOK_CHUNK_SEGMENTATION_TEMPLATE = """
你是一个专业的中医药文献分析助手。你的任务是分析提供的书籍片段，并将其内容按章节和可能的子章节进行结构化拆分。

书籍名称：《{book_title}》
当前处理的文本片段：
---
{text_chunk}
---

请按照以下要求进行处理：

1.  **识别章节和子章节**：仔细阅读文本片段，识别出主要的章节标题和结构。如果章节下有更细分的子章节（例如“节”、“小节”、“部分”等），也请一并识别。
2.  **提取信息**：对于每一个识别出的章节或子章节，请提取以下信息：
    *   `type`: 字符串，"chapter" 或 "subsection"。
    *   `title`: 字符串，章节或子章节的标题。如果无法明确找到标题（例如，只有序号或一个简单的开头），请根据内容生成一个简洁的描述性标题（不超过15个字）。
    *   `number`: 字符串，章节号（如 "1", "2"）或子章节号（如 "1.1", "1.2", "第一节", "第二节"）。如果原文中只有标题没有编号，请留空字符串 ""。
    *   `content`: 字符串，该章节或子章节的完整文本内容。
3.  **处理不完整片段**：
    *   如果文本片段的开头看起来是一个章节或子章节的延续（即，不是从一个明确的标题开始），请将其标记清楚，并尽可能从文本的实际开始处作为第一个片段的起点。
    *   如果文本片段的结尾是一个章节或子章节的一部分，且该章节或子章节明显没有结束（即，内容预计会延续到下一个文本片段中），请在最后一个条目的JSON对象中添加一个额外的键值对 `"is_incomplete": true`。如果结尾的片段是完整的，则不需要添加此键或将其设为 `false`。
4.  **输出格式**：请将结果组织成一个JSON对象列表。每个对象代表一个章节或子章节。

输出示例：
```json
[
  {
    "type": "chapter",
    "title": "第一章：基本理论",
    "number": "1",
    "content": "这里是第一章的文本内容...",
    "is_incomplete": false
  },
  {
    "type": "subsection",
    "title": "阴阳五行",
    "number": "1.1",
    "content": "阴阳五行的具体论述...",
    "is_incomplete": false
  },
  {
    "type": "subsection",
    "title": "藏象学说",
    "number": "1.2",
    "content": "关于藏象学说的详细内容，这部分内容比较长，可能没有完全结束...",
    "is_incomplete": true
  }
]
```

请确保JSON格式正确，所有字符串都使用双引号。如果文本片段中没有可识别的章节结构，请返回一个空列表 `[]`。
如果整个文本片段看起来都是一个章节的中间部分，没有明确的章节/子章节标题，那么请将整个片段视为一个单独的、可能是延续性的片段，并尝试为其生成一个描述性标题。例如：
```json
[
  {
    "type": "chapter", // 或者 "subsection" 如果上下文暗示
    "title": "某某理论的深入探讨（续）", // 生成的描述性标题
    "number": "", // 如果没有明确编号
    "content": "整个文本片段的内容...",
    "is_incomplete": true // 很可能是不完整的
  }
]
```
"""

